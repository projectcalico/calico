package cilanes

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// nonSlug matches every run of characters a set name leaves out.
var nonSlug = regexp.MustCompile(`[^a-z0-9]+`)

// ResolveSets maps every lane that runs the e2e binary to its set name. Two
// lanes claiming one name would overwrite each other's set, so that is an error.
func ResolveSets(lanes []Lane) (map[string]Lane, error) {
	sets := map[string]Lane{}
	for _, l := range lanes {
		if !l.RunsE2EBinary() {
			// run_tests.sh exits 1 on an e2e lane that selects nothing.
			if l.TestType == "k8s-e2e" && l.Area != "" {
				return nil, fmt.Errorf("%s (%s) runs the e2e binary but selects nothing", l.Name, l.Source)
			}
			continue
		}
		name, err := SetName(l)
		if err != nil {
			return nil, fmt.Errorf("%s (%s): %w", l.Name, l.Source, err)
		}
		if other, ok := sets[name]; ok {
			return nil, fmt.Errorf("%s (%s) and %s (%s) both resolve to set %s", other.Name, other.Source, l.Name, l.Source, name)
		}
		sets[name] = l
	}
	return sets, nil
}

// SetName names the lane's set after the lane itself: the sets/ subdirectory of
// the lane's source directory, the file that declares it, and the lane name
// reduced to lowercase words joined by hyphens. It fails for a source outside
// the known lane directories and for a name with nothing left to slug.
func SetName(l Lane) (string, error) {
	dir := ""
	for _, src := range laneSources {
		if src.dir == filepath.Dir(l.Source) {
			dir = src.setDir
		}
	}
	if dir == "" {
		return "", fmt.Errorf("source %q is not a known lane directory", l.Source)
	}
	file := strings.TrimSuffix(filepath.Base(l.Source), filepath.Ext(l.Source))
	lane := strings.Trim(nonSlug.ReplaceAllString(strings.ToLower(l.Name), "-"), "-")
	if lane == "" {
		return "", fmt.Errorf("lane name %q leaves nothing to name a set by", l.Name)
	}
	return dir + "/" + file + "/" + lane, nil
}

// dropsSuffix ends the name of a lane's drop list, which sits beside its set
// file. No set name can contain a dot, so it never collides with another set.
const dropsSuffix = ".drops.txt"

// Write records the index and, for each set, a file of the specs the lane runs
// and a file of the specs a suite selected that it dropped, with the reasons.
func Write(dir string, lanes []Lane, audits map[string]Audit) error {
	setsDir := filepath.Join(dir, "sets")
	if err := os.RemoveAll(setsDir); err != nil {
		return err
	}
	for name, audit := range audits {
		path := filepath.Join(setsDir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		var body string
		if len(audit.Runs) > 0 {
			body = strings.Join(audit.Runs, "\n") + "\n"
		}
		if err := os.WriteFile(path+".txt", []byte(body), 0o644); err != nil {
			return err
		}
		if err := os.WriteFile(path+dropsSuffix, []byte(FormatDrops(audit.Drops)), 0o644); err != nil {
			return err
		}
	}

	var index strings.Builder
	index.WriteString("# Generated by `make gen-test-set`. Do not edit.\n")
	index.WriteString("# ci file | lane | test set | specs\n")
	for _, l := range lanes {
		set, count := "("+l.TestType+")", "-"
		if l.Area == "" {
			set = "(no tests)"
		}
		if l.RunsE2EBinary() {
			name, err := SetName(l)
			if err != nil {
				return err
			}
			set, count = name, fmt.Sprint(len(audits[name].Runs))
		}
		fmt.Fprintf(&index, "%s | %s | %s | %s\n", l.Source, l.Name, set, count)
	}
	return os.WriteFile(filepath.Join(dir, "index.txt"), []byte(index.String()), 0o644)
}
